def build_manual(target: Path) -> Path:
    """Γράφει το εγχειρίδιο. Απαιτεί ενεργό QGuiApplication (offscreen αρκεί)."""
    target.parent.mkdir(parents=True, exist_ok=True)

    writer = QPdfWriter(str(target))
    writer.setPageSize(QPageSize(QPageSize.PageSizeId.A4))
    writer.setPageMargins(QMarginsF(16, 14, 16, 14), QPageLayout.Unit.Millimeter)
    writer.setTitle("Εγχειρίδιο χρήσης — TaxMatch by ScanMyData")
    writer.setCreator("TaxMatch by ScanMyData")
    writer.setResolution(96)

    doc = QTextDocument()
    doc.setHtml(_html())
    # Χωρίς αυτό το Qt στοιχειοθετεί σε πλάτος οθόνης και το κείμενο βγαίνει
    # έξω από το χαρτί.
    page = writer.pageLayout().paintRectPixels(writer.resolution())
    doc.setPageSize(QSizeF(page.size()))
    doc.print_(writer)
    return target


#: Ένα πραγματικό εγχειρίδιο είναι ~190KB· ένα κενό/χαλασμένο PDF είναι λίγα KB.
#: Κάτω από αυτό το κατώφλι θεωρούμε ότι το αρχείο δεν στοιχειοθετήθηκε σωστά.
_MIN_PDF_BYTES = 20_000


def _looks_built(path: Path) -> bool:
    """Αληθές αν το αρχείο μοιάζει με πραγματικό (μη κενό) PDF εγχειρίδιο."""
    try:
        if path.stat().st_size < _MIN_PDF_BYTES:
            return False
        with open(path, "rb") as handle:
            return handle.read(5) == b"%PDF-"
    except OSError:
        return False


def _bundled_manual() -> Path | None:
    """Το **έτοιμο** εγχειρίδιο μέσα στο bundle (ή στον φάκελο docs/ από πηγή).

    Το χτίζει το build.ps1 πριν το PyInstaller και μπαίνει στο bundle. Είναι πιο
    αξιόπιστο από το runtime rendering, που στο πακεταρισμένο exe έβγαζε ενίοτε
    κενό PDF.
    """
    # Μόνο το πραγματικό bundle (_MEIPASS): από πηγαίο κώδικα το docs/manual.pdf
    # μπορεί να είναι παλιό, οπότε εκεί προτιμούμε να το ξαναχτίσουμε στην εκτέλεση.
    base = getattr(sys, "_MEIPASS", "")
    if base:
        candidate = Path(base) / "manual.pdf"
        if _looks_built(candidate):
            return candidate
    return None


def ensure_manual(data_dir: Path) -> Path:
    """Η διαδρομή του εγχειριδίου, φτιάχνοντάς το αν λείπει ή αν άλλαξε.

    Γράφεται στον φάκελο δεδομένων και όχι δίπλα στο εκτελέσιμο: το Program
    Files δεν είναι εγγράψιμο για απλό χρήστη.

    Κρατάμε δίπλα του την υπογραφή του κειμένου: χωρίς αυτό, ένα εγχειρίδιο που
    φτιάχτηκε μια φορά δεν ξαναχτιζόταν ποτέ, οπότε όποια αλλαγή γράφαμε εδώ
    δεν έφτανε ποτέ σε όποιον είχε ήδη ανοίξει το PDF. Η σύγκριση γίνεται με
    hash του περιεχομένου (και όχι με ημερομηνίες): μέσα στο bundle του
    PyInstaller τα αρχεία ξεπακετάρονται με νέα ημερομηνία σε κάθε εκτέλεση.
    """
    target = data_dir / FILENAME
    stamp = data_dir / ".manual.hash"
    signature = hashlib.sha256(_html().encode("utf-8")).hexdigest()

    # Εμπιστευόμαστε το cache ΜΟΝΟ αν το αρχείο υπάρχει, είναι έγκυρο μη-κενό PDF
    # και η υπογραφή ταιριάζει. Αλλιώς ξαναχτίζεται — έτσι ένα παλιό «άδειο» PDF
    # (π.χ. από προηγούμενη έκδοση που το έγραψε κενό) δεν μένει για πάντα.
    if _looks_built(target) and stamp.exists():
        try:
            if stamp.read_text(encoding="utf-8").strip() == signature:
                return target
        except OSError:
            pass

    # Προτεραιότητα στο έτοιμο PDF του bundle — αξιόπιστο. Το runtime rendering
    # (build_manual) μένει ως εφεδρεία (π.χ. τρέξιμο από πηγαίο κώδικα χωρίς
    # bundle, ή αν λείπει το έτοιμο).
    bundled = _bundled_manual()
    if bundled is not None:
        try:
            shutil.copyfile(bundled, target)
        except OSError as exc:
            log.warning("Δεν αντιγράφηκε το έτοιμο εγχειρίδιο: %s", exc)

    if not _looks_built(target):
        build_manual(target)

    if not _looks_built(target):
        # Ούτε το έτοιμο ούτε το runtime build πέτυχαν: μη γράφεις σφραγίδα
        # (ώστε να ξαναδοκιμαστεί) και πες το καθαρά αντί να ανοίξει κενό.
        raise RuntimeError(
            "Το εγχειρίδιο δεν δημιουργήθηκε σωστά. Δοκιμάστε ξανά· αν επιμένει, "
            "στείλτε το αρχείο καταγραφής."
        )
    try:
        stamp.write_text(signature, encoding="utf-8")
    except OSError:
        # Χωρίς τη σφραγίδα απλώς θα ξαναχτίζεται — δεν είναι λόγος αποτυχίας.
        pass
    return target
