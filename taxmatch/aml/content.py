def client_kind(legal_form: str, kads: int = 1) -> str:
    """Είδος πελάτη από τη νομική μορφή (όπως τη δίνουν ΑΑΔΕ/ΓΕΜΗ/Excel). Άγνωστη μορφή -> ιδιώτης αν δεν έχει ΚΑΔ,
    αλλιώς ατομική — ο χρήστης το διορθώνει στην καρτέλα αν χρειάζεται."""
    from ..textutil import strip_accents
    lf = strip_accents(legal_form or "").upper().replace(".", "").replace(" ", "")
    if any(t in lf for t in ("TRUST", "ΙΔΡΥΜΑΑΛΛΟΔ", "ΑΛΛΟΔΑΠ")):
        return "trust"
    if any(t in lf for t in ("ΝΠΔΔ", "ΔΗΜΟΣ", "ΠΕΡΙΦΕΡΕΙΑ", "ΔΗΜΟΣΙ")):
        return "public"
    if any(t in lf for t in ("ΟΕ", "ΕΕ", "ΟΜΟΡΡΥΘΜ", "ΕΤΕΡΟΡΡΥΘΜ", "ΑΣΤΙΚ", "ΚΟΙΝΟΠΡΑΞ", "ΚΟΙΝΩΝΙΑ")) and \
            not any(t in lf for t in ("ΑΕ", "ΙΚΕ", "ΕΠΕ")):
        return "partnership"
    if any(t in lf for t in ("ΑΕ", "ΙΚΕ", "ΕΠΕ", "ΑΝΩΝΥΜ", "ΚΕΦΑΛΑΙΟΥΧ", "ΠΕΡΙΟΡΙΣΜΕΝ", "ΣΥΝΕΤΑΙΡ", "ΣΩΜΑΤΕΙ",
                                "ΝΠΙΔ", "ΝΟΜΙΚΟΠΡΟΣΩΠΟ", "ΜΚΟ", "ΙΔΡΥΜΑ")):
        return "company"
    if any(t in lf for t in ("ΙΔΙΩΤ", "ΣΥΝΤΑΞ", "ΜΙΣΘΩΤ")):
        return "individual"
    if any(t in lf for t in ("ΑΤΟΜΙΚ", "ΕΛΕΥΘΕΡ", "ΑΓΡΟΤ", "ΦΥΣΙΚ")):
        return "sole"
    return "sole" if kads else "individual"


def documents_for(legal_form: str, kind: str = "") -> tuple[tuple[str, str], ...]:
    return DOCUMENTS_BY_KIND[kind if kind in DOCUMENTS_BY_KIND else client_kind(legal_form)]


def required_documents(legal_form: str, kind: str = "") -> list[str]:
    return [k for k, _t in documents_for(legal_form, kind) if k not in OPTIONAL_DOCS]


