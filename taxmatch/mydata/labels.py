def invoice_type(code: str, short: bool = False) -> str:
    """«1.1 · Τιμολόγιο Πώλησης» (ή μόνο ο κωδικός αν δεν είναι γνωστός)."""
    name = INVOICE_TYPES.get(code or "", "")
    if short and name:
        name = name.split(" / ")[-1] if len(name) > 34 else name
    return f"{code} · {name}" if name else (code or "—")


def classification(item: dict) -> str:
    """«Έσοδα από Παροχή Υπηρεσιών (category1_3) · E3_561_001 Πωλήσεις… · 120,00 €»."""
    cat, typ = item.get("category", ""), item.get("type", "")
    parts = [f"{CATEGORIES.get(cat, cat)}" + (f" ({cat})" if cat in CATEGORIES else "") if cat else ""]
    if typ:
        parts.append(f"{typ} {E3_TYPES.get(typ, '')}".strip())
    return " · ".join(p for p in parts if p)
