def invoice_type(code: str, short: bool = False) -> str:
    """«1.1 · Τιμολόγιο Πώλησης» (ή μόνο ο κωδικός αν δεν είναι γνωστός)."""
    name = INVOICE_TYPES.get(code or "", "")
    if short and name:
        name = name.split(" / ")[-1] if len(name) > 34 else name
    return f"{code} · {name}" if name else (code or "—")


def classification(item: dict) -> str:
    """«Έσοδα από Παροχή Υπηρεσιών (category1_3) · E3_561_001 Πωλήσεις… · 120,00 €»."""
    cat, typ = item.get("category", ""), item.get("type", "")
    parts = [f"{CATEGORIES.get(cat, cat)}" + (f" ({cat})" if cat in CATEGORIES else "") if cat else ""]
    if typ:
        parts.append(f"{typ} {E3_TYPES.get(typ, '')}".strip())
    return " · ".join(p for p in parts if p)


def e3_description(type_code: str) -> str:
    """Επιστρέφει την επίσημη ελληνική περιγραφή του κωδικού Ε3 (ή τον κωδικό αν είναι άγνωστος)."""
    return E3_TYPES.get(type_code or "", type_code or "")


def category_description(cat_code: str) -> str:
    """Επιστρέφει την επίσημη περιγραφή της κατηγορίας χαρακτηρισμού (category1_*, category2_*)."""
    return CATEGORIES.get(cat_code or "", cat_code or "")


def classification_label(item: dict) -> str:
    """Συνοπτική περιγραφή χαρακτηρισμού με ελληνικές λέξεις (όχι κωδικό) για την προβολή σε πίνακα.
    Προτεραιότητα έχει η περιγραφή του Ε3 και ακολουθεί η κατηγορία."""
    cat, typ = item.get("category", ""), item.get("type", "")
    e3_desc = E3_TYPES.get(typ, "")
    cat_desc = CATEGORIES.get(cat, "")
    if e3_desc:
        return e3_desc
    if cat_desc:
        return cat_desc
    return typ or cat or "—"
