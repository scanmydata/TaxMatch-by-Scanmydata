"""Νομική μορφή από την κατάληξη της επωνυμίας («… ΜΟΝΟΠΡΟΣΩΠΗ Ι Κ Ε», «… Α.Ε.», «… O.E.») — τελευταίο fallback όταν
ούτε το ΓΕΜΗ ούτε το Μητρώο ΑΑΔΕ δίνουν νομική μορφή (το VIES δίνει μόνο επωνυμία). Δεν εφευρίσκει: αν η κατάληξη
δεν είναι σαφής, επιστρέφει ''."""
from __future__ import annotations

import re

from ..textutil import strip_accents

# Λατινικοί χαρακτήρες που μοιάζουν με ελληνικούς (οι επωνυμίες γράφονται συχνά μισο-λατινικά)
_LATIN = str.maketrans({"A": "Α", "B": "Β", "E": "Ε", "H": "Η", "I": "Ι", "K": "Κ", "M": "Μ", "N": "Ν", "O": "Ο",
                        "P": "Ρ", "T": "Τ", "X": "Χ", "Y": "Υ", "Z": "Ζ"})

# (regex πάνω στο κανονικοποιημένο τέλος της επωνυμίας, τιμή)
_LONG = [
    (r"ΙΔΙΩΤΙΚΗ ΚΕΦΑΛΑΙΟΥΧΙΚΗ ΕΤΑΙΡΕΙΑ$", "ΙΚΕ"),
    (r"ΑΝΩΝΥΜΗ ΕΤΑΙΡΕΙΑ$", "ΑΕ"),
    (r"ΕΤΑΙΡΕΙΑ ΠΕΡΙΟΡΙΣΜΕΝΗΣ ΕΥΘΥΝΗΣ$", "ΕΠΕ"),
    (r"ΟΜΟΡΡΥΘΜΗ( ΕΤΑΙΡΕΙΑ)?$", "ΟΕ"),
    (r"ΕΤΕΡΟΡΡΥΘΜΗ( ΕΤΑΙΡΕΙΑ)?$", "ΕΕ"),
]
_SHORT = [
    (r"(?:^| )Ι ?Κ ?Ε$", "ΙΚΕ"),
    (r"(?:^| )Ε ?[ΠΡ] ?Ε$", "ΕΠΕ"),                 # το λατινικό P μεταφράζεται σε Ρ (όχι Π): δεχόμαστε και τα δύο
    (r"(?:^| )Α ?Μ ?Κ ?Ε$", "ΑΜΚΕ"),
    (r"(?:^| )Κ ?Ο ?Ι ?Ν ?Σ ?Ε ?[ΠΡ]$", "ΚΟΙΝΣΕΠ"),
    (r"(?:^| )Α ?Ε$", "ΑΕ"),
    (r"(?:^| )Ο ?Ε$", "ΟΕ"),
    (r"(?:^| )Ε ?Ε$", "ΕΕ"),
]


def from_name(name: str) -> str:
    """'CHARGELINE ΜΟΝΟΠΡΟΣΩΠΗ Ι Κ Ε' -> 'ΜΟΝΟΠΡΟΣΩΠΗ ΙΚΕ'· 'ΧΧΧ Α.Ε.' -> 'ΑΕ'· αλλιώς ''."""
    text = strip_accents(str(name or "")).upper().translate(_LATIN)
    text = re.sub(r"[.,()\-]", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    if not text:
        return ""
    tail = text[-45:]
    for pattern, value in _LONG:
        if re.search(pattern, tail):
            return value
    for pattern, value in _SHORT:
        if re.search(pattern, tail):
            # Μονοπρόσωπη: υπάρχει ξεχωριστή λέξη στο τέλος («… ΜΟΝΟΠΡΟΣΩΠΗ ΙΚΕ»)
            if value in ("ΙΚΕ", "ΕΠΕ", "ΑΕ") and re.search(r"ΜΟΝΟΠΡΟΣΩΠ(Η|ΗΣ)\s+" + r"\s?".join(value) + r"$", tail):
                return "ΜΟΝΟΠΡΟΣΩΠΗ " + value
            return value
    return ""
